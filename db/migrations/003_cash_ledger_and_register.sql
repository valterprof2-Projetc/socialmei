-- SocialMEI V2 cash ledger and daily cash-register operations.
-- This migration is additive: crm_financeiro remains the receivables/payables module.
-- Run once against the Neon database after the base SocialMEI schema is present.

BEGIN;

CREATE TABLE IF NOT EXISTS socialmei.cash_transactions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  workspace_id bigint NOT NULL REFERENCES socialmei.workspaces(id) ON DELETE RESTRICT,
  appointment_id uuid,
  customer_id bigint,
  direction text NOT NULL CHECK (direction IN ('income', 'expense')),
  category varchar(80) NOT NULL,
  description varchar(240) NOT NULL,
  amount_cents bigint NOT NULL CHECK (amount_cents > 0),
  payment_method text CHECK (
    payment_method IS NULL OR payment_method IN
      ('cash', 'pix', 'credit_card', 'debit_card', 'bank_transfer', 'other')
  ),
  transaction_date date NOT NULL,
  status text NOT NULL DEFAULT 'confirmed'
    CHECK (status IN ('pending', 'confirmed', 'cancelled')),
  notes varchar(1000),
  operation_id uuid NOT NULL,
  created_by bigint REFERENCES socialmei.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT cash_transactions_workspace_operation_unique UNIQUE (workspace_id, operation_id)
);

CREATE INDEX IF NOT EXISTS cash_transactions_workspace_date_idx
  ON socialmei.cash_transactions (workspace_id, transaction_date DESC, created_at DESC);

CREATE INDEX IF NOT EXISTS cash_transactions_workspace_status_idx
  ON socialmei.cash_transactions (workspace_id, status, direction, transaction_date);

-- One operational register per business day and workspace.
CREATE TABLE IF NOT EXISTS socialmei.cash_register_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  workspace_id bigint NOT NULL REFERENCES socialmei.workspaces(id) ON DELETE RESTRICT,
  business_date date NOT NULL,
  opening_amount_cents bigint NOT NULL CHECK (opening_amount_cents >= 0),
  closing_amount_cents bigint CHECK (closing_amount_cents >= 0),
  expected_cash_cents bigint CHECK (expected_cash_cents >= 0),
  difference_cents bigint,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'closed')),
  opened_by bigint REFERENCES socialmei.users(id) ON DELETE SET NULL,
  closed_by bigint REFERENCES socialmei.users(id) ON DELETE SET NULL,
  opened_at timestamptz NOT NULL DEFAULT now(),
  closed_at timestamptz,
  CONSTRAINT cash_register_sessions_workspace_day_unique UNIQUE (workspace_id, business_date),
  CONSTRAINT cash_register_sessions_close_state_check CHECK (
    (status = 'open' AND closed_at IS NULL AND closing_amount_cents IS NULL)
    OR
    (status = 'closed' AND closed_at IS NOT NULL AND closing_amount_cents IS NOT NULL
      AND expected_cash_cents IS NOT NULL AND difference_cents IS NOT NULL)
  )
);

CREATE TABLE IF NOT EXISTS socialmei.cash_register_movements (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  workspace_id bigint NOT NULL REFERENCES socialmei.workspaces(id) ON DELETE RESTRICT,
  session_id uuid NOT NULL REFERENCES socialmei.cash_register_sessions(id) ON DELETE RESTRICT,
  movement_type text NOT NULL CHECK (
    movement_type IN ('supply', 'withdrawal', 'adjustment')
  ),
  amount_cents bigint NOT NULL CHECK (amount_cents > 0),
  description varchar(240) NOT NULL,
  operation_id uuid NOT NULL,
  created_by bigint REFERENCES socialmei.users(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT cash_register_movements_session_operation_unique UNIQUE (session_id, operation_id)
);

CREATE INDEX IF NOT EXISTS cash_register_sessions_workspace_date_idx
  ON socialmei.cash_register_sessions (workspace_id, business_date DESC);

CREATE INDEX IF NOT EXISTS cash_register_movements_workspace_session_idx
  ON socialmei.cash_register_movements (workspace_id, session_id, created_at);

-- Management balance from confirmed ledger entries; CRM receivables/payables are separate.
CREATE OR REPLACE VIEW socialmei.v_cash_balance AS
SELECT
  workspace_id,
  COALESCE(SUM(CASE WHEN direction = 'income' THEN amount_cents ELSE -amount_cents END), 0)::bigint
    AS balance_cents,
  COALESCE(SUM(CASE WHEN payment_method = 'cash' AND direction = 'income'
                    THEN amount_cents
                    WHEN payment_method = 'cash' AND direction = 'expense'
                    THEN -amount_cents ELSE 0 END), 0)::bigint
    AS cash_on_hand_movement_cents
FROM socialmei.cash_transactions
WHERE status = 'confirmed'
GROUP BY workspace_id;

COMMIT;
